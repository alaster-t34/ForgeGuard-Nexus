def ensure_csv_size(size: int, policy: CsvPolicy) -> None:
    if size > policy.max_bytes:
        raise ValueError(
            f"CSV file exceeds the {policy.max_bytes // MIB} MB limit for {policy.name}"
        )


def decode_csv_bytes(content: bytes, policy: CsvPolicy) -> tuple[str, str]:
    ensure_csv_size(len(content), policy)
    if content.startswith((codecs.BOM_UTF16_LE, codecs.BOM_UTF16_BE)):
        try:
            return content.decode("utf-16"), "utf-16"
        except UnicodeDecodeError as exc:
            raise ValueError("CSV has an invalid UTF-16 byte sequence") from exc
    for encoding in policy.encodings:
        if encoding == "utf-16":
            continue
        try:
            return content.decode(encoding), encoding
        except UnicodeDecodeError:
            continue
    readable = ", ".join(policy.encodings)
    raise ValueError(f"CSV encoding is not supported; use {readable}")


def sniff_csv_dialect(text: str, policy: CsvPolicy) -> csv.Dialect:
    try:
        return csv.Sniffer().sniff(text[:16_384], delimiters="".join(policy.delimiters))
    except csv.Error:
        class DefaultDialect(csv.excel):
            delimiter = policy.delimiters[0]

        return DefaultDialect()


