from __future__ import annotations

import codecs
import csv
from dataclasses import asdict, dataclass


MIB = 1024 * 1024


@dataclass(frozen=True, slots=True)
class CsvPolicy:
    name: str
    max_bytes: int
    max_rows: int
    max_columns: int
    max_cell_characters: int
    encodings: tuple[str, ...]
    delimiters: tuple[str, ...]
    header: str
    notes: str

    def public(self) -> dict[str, object]:
        payload = asdict(self)
        payload["max_size_mb"] = self.max_bytes // MIB
        return payload


